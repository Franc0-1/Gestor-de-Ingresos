type accountFake struct {
	accounts map[int64]models.Account
	nextID   int64
	calls    int
	errors   map[string]error
}

func newAccountFake() *accountFake {
	return &accountFake{accounts: make(map[int64]models.Account), errors: make(map[string]error)}
}

func (f *accountFake) Create(a models.Account) (models.Account, error) {
	f.calls++
	if err := f.errors["create"]; err != nil {
		return models.Account{}, err
	}
	f.nextID++
	a.ID = f.nextID
	f.accounts[a.ID] = a
	return a, nil
}
func (f *accountFake) GetAll() ([]models.Account, error) {
	f.calls++
	if err := f.errors["all"]; err != nil {
		return nil, err
	}
	var accounts []models.Account
	for _, a := range f.accounts {
		accounts = append(accounts, a)
	}
	return accounts, nil
}
func (f *accountFake) GetByID(id int64) (models.Account, error) {
	f.calls++
	if err := f.errors["get"]; err != nil {
		return models.Account{}, err
	}
	a, ok := f.accounts[id]
	if !ok {
		return models.Account{}, fmt.Errorf("ID %d: %w", id, repository.ErrNotFound)
	}
	return a, nil
}
func (f *accountFake) Update(a models.Account) error {
	f.calls++
	if err := f.errors["update"]; err != nil {
		return err
	}
	if _, ok := f.accounts[a.ID]; !ok {
		return repository.ErrNotFound
	}
	// Emulate the repository assigning its own timestamp at persistence time.
	a.UpdatedAt = a.UpdatedAt.Add(time.Millisecond)
	f.accounts[a.ID] = a
	return nil
}
func (f *accountFake) Delete(id int64) error {
	f.calls++
	if err := f.errors["delete"]; err != nil {
		return err
	}
	if _, ok := f.accounts[id]; !ok {
		return repository.ErrNotFound
	}
	delete(f.accounts, id)
	return nil
}

func validAccount() models.Account {
	return models.Account{Name: "Mercado Pago", Type: "wallet", Currency: "ARS", InitialBalance: 1500000, Active: true}
}

func TestAccountServiceCreate(t *testing.T) {
	fake := newAccountFake()
	s := NewAccountService(fake)
	a := validAccount()
	a.Name = "  Mercado Pago \t"
	a.Type = " WALLET "
	a.Currency = " ars "
	a.ID = 99
	a.CreatedAt = time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC)
	a.UpdatedAt = a.CreatedAt
	a.InitialBalance = math.MaxInt64
	before := time.Now().UTC()
	got, err := s.Create(a)
	if err != nil {
		t.Fatal(err)
	}
	if got.ID != 1 || got.Name != "Mercado Pago" || got.Type != "wallet" || got.Currency != "ARS" || got.InitialBalance != math.MaxInt64 || !got.Active {
		t.Fatalf("incorrect creation: %+v", got)
	}
	if got.CreatedAt.Before(before) || !got.CreatedAt.Equal(got.UpdatedAt) || got.CreatedAt.After(time.Now()) {
		t.Fatalf("timestamps not generated by backend: %+v", got)
	}
	if fake.accounts[1] != got {
		t.Fatal("created account not persisted")
	}
}

func TestAccountServiceValidation(t *testing.T) {
	for _, field := range []string{"Name", "Type", "Currency"} {
		for _, operation := range []string{"Create", "Update"} {
			t.Run(operation+field, func(t *testing.T) {
				fake := newAccountFake()
				s := NewAccountService(fake)
				a := validAccount()
				switch field {
				case "Name":
					a.Name = " \t"
				case "Type":
					a.Type = "credit"
				case "Currency":
					a.Currency = " "
				}
				var err error
				if operation == "Create" {
					_, err = s.Create(a)
				} else {
					_, err = s.Update(1, a)
				}
				var validation *models.ValidationError
				if !errors.As(err, &validation) || validation.Field != field {
					t.Fatalf("expected %s validation: %v", field, err)
				}
				if fake.calls != 0 {
					t.Fatal("invalid model reached repository")
				}
			})
		}
	}
	for _, id := range []int64{0, -1} {
		fake := newAccountFake()
		s := NewAccountService(fake)
		_, getErr := s.GetByID(id)
		_, updateErr := s.Update(id, validAccount())
		for _, err := range []error{getErr, updateErr, s.Delete(id)} {
			var validation *models.ValidationError
			if !errors.As(err, &validation) || validation.Field != "ID" {
				t.Fatalf("invalid ID accepted: %v", err)
			}
		}
		if fake.calls != 0 {
			t.Fatal("invalid ID reached repository")
		}
	}
}

func TestAccountServiceCRUD(t *testing.T) {
	fake := newAccountFake()
	s := NewAccountService(fake)
	empty, err := s.GetAll()
	if err != nil || empty == nil || len(empty) != 0 {
		t.Fatalf("empty array: %v %v", empty, err)
	}
	created, err := s.Create(validAccount())
	if err != nil {
		t.Fatal(err)
	}
	got, err := s.GetByID(created.ID)
	if err != nil || got != created {
		t.Fatalf("GetByID: %+v %v", got, err)
	}
	all, err := s.GetAll()
	if err != nil || len(all) != 1 || all[0] != created {
		t.Fatalf("GetAll: %v %v", all, err)
	}
	a := validAccount()
	a.ID = 999
	a.Name = " Banco "
	a.Type = " bank "
	a.Active = false
	a.InitialBalance = -1050025
	a.CreatedAt = time.Now().Add(-time.Hour)
	updated, err := s.Update(created.ID, a)
	if err != nil {
		t.Fatal(err)
	}
	if updated.ID != created.ID || updated.Name != "Banco" || updated.Type != "bank" || updated.Active || updated.InitialBalance != -1050025 || !updated.CreatedAt.Equal(created.CreatedAt) || !updated.UpdatedAt.After(created.UpdatedAt) {
		t.Fatalf("incorrect update: %+v", updated)
	}
	if updated != fake.accounts[created.ID] {
		t.Fatal("Update did not return persisted account")
	}
	if err := s.Delete(created.ID); err != nil {
		t.Fatal(err)
	}
	_, getErr := s.GetByID(created.ID)
	_, updateErr := s.Update(created.ID, validAccount())
	for _, err := range []error{getErr, updateErr, s.Delete(created.ID)} {
		if !errors.Is(err, repository.ErrNotFound) {
			t.Fatalf("ErrNotFound not propagated: %v", err)
		}
	}
}

func TestAccountServiceRepositoryErrors(t *testing.T) {
	for _, operation := range []string{"create", "all", "get", "update", "delete"} {
		t.Run(operation, func(t *testing.T) {
			fake := newAccountFake()
			fake.accounts[1] = validAccount()
			failure := errors.New("repository unavailable")
			fake.errors[operation] = failure
			s := NewAccountService(fake)
			var err error
			switch operation {
			case "create":
				_, err = s.Create(validAccount())
			case "all":
				_, err = s.GetAll()
			case "get":
				_, err = s.GetByID(1)
			case "update":
				_, err = s.Update(1, validAccount())
			case "delete":
				err = s.Delete(1)
			}
			if !errors.Is(err, failure) {
				t.Fatalf("repository error not propagated: %v", err)
			}
		})
	}
}
